"""Generate a tiny synthetic AHAAR-Fridge dataset for pipeline smoke-testing.

This is NOT real training data. The images are plain-colour rectangles
labelled against the 20 AHAAR-Fridge classes so that `python training/
train.py --config ...` runs end-to-end in a couple of minutes, proving
the pipeline works before you invest days in shooting real photos.

    python datasets/scripts/make_smoke_dataset.py

Writes:
    data/images/train/*.png  (48 images)
    data/images/val/*.png    (20 images)
    data/labels/train/*.txt  (YOLO-format labels, one per image)
    data/labels/val/*.txt
    data/images/train/.AHAAR_SMOKE_MARKER   (do not train for real on this)

Delete the four train/val subdirs (or just the .png/.txt files inside)
before you shoot real data. The .AHAAR_SMOKE_MARKER file is a tripwire:
anything checking for it should refuse to upload weights derived from
smoke data to Hugging Face / production.

Standard library only (no Pillow dep): we write minimal 1-bit PNGs by
hand via zlib. Each image is 128x128 px with up to 3 solid-colour
rectangles placed on it; the rectangles' positions become the YOLO
labels.
"""
from __future__ import annotations

import random
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IMG_DIR = ROOT / "data/images"
LBL_DIR = ROOT / "data/labels"
MARKER  = IMG_DIR / "train" / ".AHAAR_SMOKE_MARKER"

NUM_CLASSES = 20          # matches datasets/ahaar-fridge.yaml
TRAIN_IMAGES = 48
VAL_IMAGES   = 20
WIDTH = HEIGHT = 128
SEED = 42

# Deterministic per-class RGB so the smoke model has *something* to learn.
PALETTE = [
    (200,  80,  60), (230, 170,  50), (170, 110,  70), ( 90, 130,  80),
    (110, 170,  80), (170, 180, 110), (120,  80,  40), (200, 200, 200),
    (230, 230, 210), (210, 160,  80), (160, 180, 210), (180, 160, 110),
    (140, 200, 170), (240, 220, 170), (190, 140, 170), ( 70, 120, 130),
    (210, 110, 110), (150, 150, 130), (220, 200, 150), ( 80, 160, 140),
]
assert len(PALETTE) == NUM_CLASSES


def write_png(path: Path, w: int, h: int, rgb_rows: list[bytes]) -> None:
    """Minimal RGB PNG writer: IHDR + IDAT + IEND. One chunk per row."""
    def chunk(tag: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(tag + data)
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)

    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)  # 8-bit RGB
    raw = b"".join(b"\x00" + row for row in rgb_rows)   # filter byte 0
    idat = zlib.compress(raw, 6)
    path.write_bytes(sig + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b""))


def make_image(rng: random.Random) -> tuple[list[bytes], list[tuple[int, float, float, float, float]]]:
    """Return (row bytes, labels) for one synthetic image.
    Labels: list of (class_id, xc, yc, w, h) normalised 0-1."""
    # Cream background matching AHAAR brand (#FBF6EC).
    bg_r, bg_g, bg_b = 0xFB, 0xF6, 0xEC
    pixels = bytearray([bg_r, bg_g, bg_b] * (WIDTH * HEIGHT))

    n = rng.randint(1, 3)
    labels: list[tuple[int, float, float, float, float]] = []
    for _ in range(n):
        cid = rng.randrange(NUM_CLASSES)
        cr, cg, cb = PALETTE[cid]
        # 20-40 px wide rectangles at random positions, clamped inside.
        rw = rng.randint(20, 40)
        rh = rng.randint(20, 40)
        rx = rng.randint(0, WIDTH - rw)
        ry = rng.randint(0, HEIGHT - rh)
        for y in range(ry, ry + rh):
            off = (y * WIDTH + rx) * 3
            for x in range(rw):
                pixels[off + x * 3]     = cr
                pixels[off + x * 3 + 1] = cg
                pixels[off + x * 3 + 2] = cb
        xc = (rx + rw / 2) / WIDTH
        yc = (ry + rh / 2) / HEIGHT
        labels.append((cid, xc, yc, rw / WIDTH, rh / HEIGHT))

    # Split into row bytes
    rows = [bytes(pixels[y * WIDTH * 3:(y + 1) * WIDTH * 3]) for y in range(HEIGHT)]
    return rows, labels


def write_split(split: str, n: int, rng: random.Random) -> None:
    img_out = IMG_DIR / split
    lbl_out = LBL_DIR / split
    img_out.mkdir(parents=True, exist_ok=True)
    lbl_out.mkdir(parents=True, exist_ok=True)
    for i in range(n):
        rows, labels = make_image(rng)
        stem = f"smoke_{i:04d}"
        write_png(img_out / f"{stem}.png", WIDTH, HEIGHT, rows)
        (lbl_out / f"{stem}.txt").write_text(
            "\n".join(f"{c} {xc:.4f} {yc:.4f} {w:.4f} {h:.4f}" for c, xc, yc, w, h in labels) + "\n",
            encoding="utf-8",
        )


def main() -> None:
    rng = random.Random(SEED)
    write_split("train", TRAIN_IMAGES, rng)
    write_split("val",   VAL_IMAGES,   rng)
    MARKER.parent.mkdir(parents=True, exist_ok=True)
    MARKER.write_text(
        "This folder holds AHAAR smoke-test data generated by\n"
        "datasets/scripts/make_smoke_dataset.py — NOT real training images.\n"
        "Delete the .png and .txt files here before shooting AHAAR-Fridge.\n",
        encoding="utf-8",
    )
    print(f"[smoke] wrote {TRAIN_IMAGES} train + {VAL_IMAGES} val PNGs "
          f"({WIDTH}x{HEIGHT}, {NUM_CLASSES} classes) under data/")
    print(f"[smoke] marker file at {MARKER.relative_to(ROOT)}")
    print("[smoke] now run:  python training/train.py --config training/configs/yolov8m_baseline.yaml")


if __name__ == "__main__":
    main()
